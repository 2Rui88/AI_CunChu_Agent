def build_docx(spec: dict, out_path: Path) -> int:
    """按 spec 生成 docx,返回全部正文字符数(标题+章节标题+段落)。"""
    doc = Document()

    # 正文默认样式:小四、宋体、1.3 倍行距
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(12)
    style._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")

    title = doc.add_heading(spec["title"], level=0)
    for run in title.runs:
        run.font.name = "Times New Roman"
        run._element.rPr.rFonts.set(qn("w:eastAsia"), "黑体")

    total = len(spec["title"])
    for heading, paras in spec["sections"]:
        h = doc.add_heading(heading, level=1)
        for run in h.runs:
            run.font.name = "Times New Roman"
            run._element.rPr.rFonts.set(qn("w:eastAsia"), "黑体")
        total += len(heading)
        for para in paras:
            p = doc.add_paragraph(para)
            p.paragraph_format.first_line_indent = Pt(24)  # 2 字符(小四)
            p.paragraph_format.line_spacing = 1.3
            total += len(para)

    doc.save(str(out_path))
    return total


def parse_like_backend(path: Path) -> tuple[int, str]:
    """与修复后后端 _parse_docx 相同的提取逻辑,返回 (字符数, 提取文本前80字符)。"""
    with zipfile.ZipFile(io.BytesIO(path.read_bytes())) as zf:
        xml_bytes = zf.read("word/document.xml")
    try:
        xml_text = xml_bytes.decode("utf-8")
    except UnicodeDecodeError:
        xml_text = xml_bytes.decode("latin-1")
    paras = []
    for p_match in re.finditer(r"<w:p[ >].*?</w:p>", xml_text, re.DOTALL):
        parts = re.findall(r"<w:t(?: [^>]*)?>(.*?)</w:t>", p_match.group())
        if parts:
            paras.append("".join(parts))
    text = "\n".join(paras).strip()
    return len(text), text[:80]


def main():
    ok = True
    seen_texts = []
    for spec in DOCS:
        out = OUT_DIR / spec["filename"]
        declared = build_docx(spec, out)
        extracted, head = parse_like_backend(out)
        dup = any(t.startswith(head[:60]) for t in seen_texts)
        seen_texts.append(head)
        status = "OK" if extracted >= 3500 and not dup else "FAIL"
        if status == "FAIL":
            ok = False
        print(f"[{status}] {spec['filename']} 排版字符数={declared} 后端可提取字符数={extracted}")
    raise SystemExit(0 if ok else 1)


if __name__ == "__main__":
    main()
